#!/usr/bin/env python3
"""Generate the brain frontend's WinUI-mode toolbar icon set.

Same generation method as make_icons.py (the Material set):
the glyphs are NOT drawn here.  They are the official Fluent UI
System Icons (regular style, 24px grid; MIT - see
assets/icons/MANIFEST.md for the per-icon source paths), rasterised
at 4x and downscaled to 28px with LANCZOS for antialiasing, then
tinted with the alpha channel carrying the coverage.  Emitted as
canvas-packed uint32 arrays (a<<24)|(r<<16)|(g<<8)|b for
tk_button_set_icon().

Renderer difference from make_icons.py: cairosvg is not installed
on this host, so the 4x rasterisation uses the icon pipeline's own
established renderer, assets/icons/tools/svg2png (librsvg + cairo,
the tool assets/icons/build_icons.py builds every shipped icon
PNG with).  Supersampling factor, final size, LANCZOS downscale,
tinting and packing are identical to make_icons.py.

The baked tint is #212121 (the Fluent source ink).  The toolbar
re-tints every icon to the active theme's text_dim at chrome
build time (the alpha channel is the shape; see toolbar.c), so
the same arrays serve the WinUI light and dark themes.

Sources:  ../../../assets/icons/src/fluent/<name>.svg
Output:   netsurf/frontends/brain/icons_winui.h
Also writes icons-winui-preview.png next to this script.
"""
import io
import os
import subprocess
import sys
import tempfile

from PIL import Image

S = 4              # supersample, as in make_icons.py
N = 28             # final icon size (px)
COL = (33, 33, 33)  # #212121, the Fluent source ink

HERE = os.path.dirname(os.path.abspath(__file__))
REBUILD = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(REBUILD, "assets", "icons", "src", "fluent")
SVG2PNG = os.path.join(REBUILD, "assets", "icons", "tools", "svg2png")

# output name -> fluent source stem (assets/icons/src/fluent/)
ICONS = [
    ("back", "arrow_left"),
    ("forward", "arrow_right"),
    ("reload", "arrow_clockwise"),
    ("stop", "dismiss"),
    ("home", "home"),
    ("menu", "more_horizontal"),
    ("plus", "add"),
    ("star", "star"),
]


def render(stem):
    svg_path = os.path.join(SRC, stem + ".svg")
    if not os.path.exists(svg_path):
        sys.exit("missing source SVG: %s" % svg_path)
    with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as tf:
        big_path = tf.name
    try:
        subprocess.run([SVG2PNG, svg_path, big_path, str(N * S)],
                       check=True)
        img = Image.open(big_path).convert("RGBA")
    finally:
        os.unlink(big_path)
    master = img.copy()
    if master.size != (N * S, N * S):
        master = master.resize((N * S, N * S), Image.LANCZOS)
    small = master.resize((N, N), Image.LANCZOS)
    # Tint: colour is COL everywhere; alpha = coverage (the source
    # is dark-on-transparent, so the rendered alpha IS the coverage).
    px = small.load()
    for y in range(N):
        for x in range(N):
            _r, _g, _b, a = px[x, y]
            px[x, y] = COL + (a,)
    return small, master


def pack(img):
    px = img.load()
    vals = []
    for y in range(N):
        for x in range(N):
            r, g, b, a = px[x, y]
            vals.append("0x%08xu" % ((a << 24) | (r << 16) | (g << 8) | b))
    return vals


def main():
    if not os.path.exists(SVG2PNG):
        sys.exit("renderer missing: %s (see assets/icons/build_icons.py)"
                 % SVG2PNG)
    out = os.path.join(HERE, "..", "netsurf-all-3.11", "netsurf",
                       "frontends", "brain", "icons_winui.h")
    lines = [
        "/* Generated by test-harness/make_icons_winui.py - do not edit.",
        " * Glyphs: official Fluent UI System Icons (regular, 24px grid),",
        " * MIT; sources in ../../../assets/icons/src/fluent/ (see",
        " * assets/icons/MANIFEST.md).  Rasterised at 4x with librsvg",
        " * (assets/icons/tools/svg2png) and downscaled to 28px with",
        " * LANCZOS, the make_icons.py method; tint #212121 baked in,",
        " * alpha carries the coverage (toolbar.c re-tints to the",
        " * active theme's text_dim at build time). */",
        "#ifndef BRAIN_ICONS_WINUI_H",
        "#define BRAIN_ICONS_WINUI_H",
        "#include <stdint.h>",
        "#define BRAIN_ICON_WINUI_SIZE %d" % N,
        "",
    ]
    sheet = Image.new("RGBA", (len(ICONS) * (N * S + 8) + 8,
                               N * S + N + 24), (255, 255, 255, 255))
    for i, (name, stem) in enumerate(ICONS):
        img, master = render(stem)
        cov = sum(img.load()[x, y][3] for y in range(N) for x in range(N))
        if cov == 0:
            sys.exit("icon %s (%s) rendered empty" % (name, stem))
        vals = pack(img)
        lines.append("static const uint32_t brain_icon_winui_%s[%d] = {"
                     % (name, N * N))
        for j in range(0, len(vals), 7):
            lines.append("\t" + ", ".join(vals[j:j + 7]) + ",")
        lines.append("};")
        lines.append("")
        x0 = 8 + i * (N * S + 8)
        sheet.paste(master, (x0, 8), master)
        native = Image.new("RGBA", (N, N), (255, 255, 255, 255))
        native.paste(img, (0, 0), img)
        sheet.paste(native, (x0, N * S + 16))
        print("%-8s <- fluent/%s.svg  coverage=%d" % (name, stem, cov))
    lines.append("#endif")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    sheet.convert("RGB").save(os.path.join(HERE, "icons-winui-preview.png"))
    print("wrote", out)


if __name__ == "__main__":
    main()
