#!/usr/bin/env python3
"""Generate the brain frontend's toolbar icon set as a C header.

The glyphs are NOT drawn here.  They are the official Google Material
Icons (filled style, 24px grid; Apache 2.0 — see material-icons/
README.md for the per-icon source paths), rasterised with cairosvg at
4x and downscaled to 28px with LANCZOS for antialiasing, then tinted
to the UI-STYLE-v2 on-surface-variant colour #49454F with the alpha
channel carrying the coverage.  Emitted as canvas-packed uint32
arrays (a<<24)|(r<<16)|(g<<8)|b for tk_button_set_icon().

Requires: cairosvg (pip install cairosvg) and Pillow.
Output: netsurf/frontends/brain/icons.h
Also writes icons-preview.png next to this script (audit sheet:
each glyph at native 28px on white, plus the 112px master render).
"""
import io
import os
import sys

try:
    import cairosvg
except ImportError:
    sys.exit("cairosvg is required: pip install cairosvg")
from PIL import Image

S = 4              # supersample
N = 28             # final icon size (px)
COL = (73, 69, 79)  # #49454F

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "material-icons")
ICONS = ["back", "forward", "reload", "stop",
         "home", "menu", "plus", "star"]


def render(name):
    svg_path = os.path.join(SRC, name + ".svg")
    png = cairosvg.svg2png(url=svg_path,
                           output_width=N * S, output_height=N * S)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    master = img.copy()
    small = img.resize((N, N), Image.LANCZOS)
    # Tint: colour is COL everywhere; alpha = coverage (the source is
    # black-on-transparent, so the rendered alpha IS the coverage).
    px = small.load()
    for y in range(N):
        for x in range(N):
            _r, _g, _b, a = px[x, y]
            px[x, y] = COL + (a,)
    return small, master


def pack(img):
    px = img.load()
    vals = []
    for y in range(N):
        for x in range(N):
            r, g, b, a = px[x, y]
            vals.append("0x%08xu" % ((a << 24) | (r << 16) | (g << 8) | b))
    return vals


def main():
    out = os.path.join(HERE, "..", "netsurf-all-3.11", "netsurf",
                       "frontends", "brain", "icons.h")
    lines = [
        "/* Generated by test-harness/make_icons.py - do not edit.",
        " * Glyphs: official Google Material Icons (filled, 24px grid),",
        " * Apache 2.0; sources in test-harness/material-icons/. */",
        "#ifndef BRAIN_ICONS_H",
        "#define BRAIN_ICONS_H",
        "#include <stdint.h>",
        "#define BRAIN_ICON_SIZE %d" % N,
        "",
    ]
    sheet = Image.new("RGBA", (len(ICONS) * (N * S + 8) + 8,
                               N * S + N + 24), (255, 255, 255, 255))
    for i, name in enumerate(ICONS):
        img, master = render(name)
        vals = pack(img)
        lines.append("static const uint32_t brain_icon_%s[%d] = {"
                     % (name, N * N))
        for j in range(0, len(vals), 7):
            lines.append("\t" + ", ".join(vals[j:j + 7]) + ",")
        lines.append("};")
        lines.append("")
        x0 = 8 + i * (N * S + 8)
        sheet.paste(master, (x0, 8), master)
        native = Image.new("RGBA", (N, N), (255, 255, 255, 255))
        native.paste(img, (0, 0), img)
        sheet.paste(native, (x0, N * S + 16))
    lines.append("#endif")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    sheet.convert("RGB").save(os.path.join(HERE, "icons-preview.png"))
    print("wrote", out)


if __name__ == "__main__":
    main()
