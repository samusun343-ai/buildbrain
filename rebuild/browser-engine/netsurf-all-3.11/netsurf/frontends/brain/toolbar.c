static void on_menu_select(tk_widget *w, void *ud)
{
	int id = tk_menu_last_id(w);
	struct gui_window *gw = brain_fe.active;

	(void)ud;
	switch (id) {
	case MENU_NEW_TAB:
		on_new_tab(NULL, NULL);
		break;
	case MENU_BOOKMARK_TOGGLE:
		if (gw != NULL) {
			nsurl *url = browser_window_access_url(gw->bw);
			if (url != NULL) {
				if (hotlist_has_url(url)) {
					hotlist_remove_url(url);
				} else {
					hotlist_add_url(url);
				}
			}
		}
		break;
	case MENU_BOOKMARKS:
		open_bookmarks();
		break;
	case MENU_HISTORY:
		open_history();
		break;
	case MENU_HOME:
		go_home();
		break;
	case MENU_SETTINGS:
		open_settings();
		break;
	case MENU_CLOSE_TAB:
		brain_close_active_window();
		break;
	case MENU_QUIT:
		brain_quit();
		break;
	default:
		break;
	}
}

static void on_menu_button(tk_widget *w, void *ud)
{
	tk_rect r;
	struct gui_window *gw = brain_fe.active;
	bool bookmarked = false;

	(void)ud;
	if (gw != NULL) {
		nsurl *url = browser_window_access_url(gw->bw);
		if (url != NULL) {
			bookmarked = hotlist_has_url(url);
		}
	}
	/* rebuild the menu each time so the bookmark toggle label
	 * reflects the current page */
	tk_widget_free(menu_widget);
	menu_widget = tk_menu_new();
	tk_menu_add_item(menu_widget, "新規タブ", MENU_NEW_TAB);
	tk_menu_add_check_item(menu_widget,
			bookmarked ? "ブックマークから削除" :
				"ブックマークに追加",
			MENU_BOOKMARK_TOGGLE, bookmarked);
	tk_menu_add_item(menu_widget, "ブックマーク…", MENU_BOOKMARKS);
	tk_menu_add_item(menu_widget, "履歴…", MENU_HISTORY);
	tk_menu_add_item(menu_widget, "ホームを開く", MENU_HOME);
	tk_menu_add_separator(menu_widget);
	tk_menu_add_item(menu_widget, "設定…", MENU_SETTINGS);
	tk_menu_add_item(menu_widget, "タブを閉じる", MENU_CLOSE_TAB);
	tk_menu_add_item(menu_widget, "終了", MENU_QUIT);
	tk_menu_set_on_select(menu_widget, on_menu_select, NULL);

	r = tk_widget_rect(w);
	tk_menu_popup(brain_fe.root, menu_widget, r.x + r.w - 220,
			r.y + r.h + 4);
}

