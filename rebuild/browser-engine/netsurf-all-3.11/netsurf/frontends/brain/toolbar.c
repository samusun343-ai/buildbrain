/* collected entries for the open dialog (owned strings) */
#define MAX_LIST_ENTRIES 200
static char *list_urls[MAX_LIST_ENTRIES];
static char *list_titles[MAX_LIST_ENTRIES];
static int list_count;

static void list_clear(void)
{
	int i;
	for (i = 0; i < list_count; i++) {
		free(list_urls[i]);
		free(list_titles[i]);
		list_urls[i] = NULL;
		list_titles[i] = NULL;
	}
	list_count = 0;
}

static void list_push(const char *url, const char *title)
{
	if (list_count >= MAX_LIST_ENTRIES || url == NULL) {
		return;
	}
	list_urls[list_count] = strdup(url);
	list_titles[list_count] = strdup(
		(title != NULL && title[0] != '\0') ? title : url);
	list_count++;
}

