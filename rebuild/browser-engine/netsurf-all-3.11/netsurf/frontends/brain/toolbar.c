void brain_chrome_layout(void)
{
	if (brain_fe.page_holder == NULL) {
		return;
	}
	{
		tk_rect pr = tk_widget_rect(brain_fe.page_holder);

		/* progress: 3px line across the page's top edge */
		if (brain_fe.progress != NULL) {
			tk_set_fixed_rect(brain_fe.progress,
					(tk_rect){ 0, 0, pr.w, 3 });
		}
		/* status bubble: bottom-left overlay in the page */
		if (brain_fe.status_bubble != NULL) {
			int bw = pr.w - 16;
			if (bw > 560) bw = 560;
			if (bw < 0) bw = 0;
			tk_set_fixed_rect(brain_fe.status_bubble,
					(tk_rect){ 8, pr.h - 36, bw, 28 });
		}
	}
}

