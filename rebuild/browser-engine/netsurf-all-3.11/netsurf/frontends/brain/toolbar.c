/* display mode: Android (Material) vs WinUI (Fluent)                 */
/*                                                                    */
/* brain_fe.winui is set once in gui.c from brainreg ui/mode via      */
/* bd_theme_from_reg(); the theme carries colours, corner radii       */
/* (radius_button 999 pill vs 6), field style (filled pill vs         */
/* outlined) and type sizes, so the chrome below only branches on     */
/* (a) toolbar composition and (b) which icon set a button gets.      */
/* Icons are established vector glyphs only: Material (icons.h,       */
/* generated by test-harness/make_icons.py) or Fluent                 */
/* (icons_winui.h, generated by test-harness/make_icons_winui.py      */
/* from assets/icons/src/fluent/).  Both sets bake an ink colour      */
/* into the array, so the selected glyph is re-tinted here to the     */
/* active theme's text_dim - the alpha channel is the shape and is    */
/* preserved verbatim (the same tinting bdicon performs for the       */
/* apps).  tk_button_set_icon() copies the pixels, so the shared      */
/* per-slot buffers below are safe to reuse across buttons.           */
/* ------------------------------------------------------------------ */

typedef char brain_icon_size_check[
	(BRAIN_ICON_SIZE == BRAIN_ICON_WINUI_SIZE) ? 1 : -1];

enum {
	ICON_SLOT_BACK, ICON_SLOT_FWD, ICON_SLOT_RELOAD, ICON_SLOT_STOP,
	ICON_SLOT_HOME, ICON_SLOT_MENU, ICON_SLOT_PLUS, ICON_SLOT_STAR,
	ICON_SLOT_COUNT
};

static uint32_t icon_tinted[ICON_SLOT_COUNT][BRAIN_ICON_SIZE *
		BRAIN_ICON_SIZE];

static const uint32_t *icon_tint(int slot, const uint32_t *src,
		tk_color ink)
{
	uint32_t rgb = ((uint32_t)ink.r << 16) | ((uint32_t)ink.g << 8) |
			(uint32_t)ink.b;
	int i;
	for (i = 0; i < BRAIN_ICON_SIZE * BRAIN_ICON_SIZE; i++) {
		icon_tinted[slot][i] = (src[i] & 0xFF000000u) | rgb;
	}
	return icon_tinted[slot];
}

/* The mode's glyph for one toolbar role, tinted with `ink`. */
static const uint32_t *icon_for(int slot, const uint32_t *material,
		const uint32_t *fluent, tk_color ink)
{
	return icon_tint(slot,
			brain_fe.winui ? fluent : material, ink);
}

static const uint32_t *icon_default(int slot, const uint32_t *material,
		const uint32_t *fluent)
{
	return icon_for(slot, material, fluent,
			tk_theme_default()->text_dim);
}

