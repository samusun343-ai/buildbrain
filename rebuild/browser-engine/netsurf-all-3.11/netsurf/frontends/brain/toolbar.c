/* Copy one nsurl component into a plain buffer (the getter hands
 * out a referenced lwc_string).  Returns false when the URL has
 * no such component. */
static bool url_component(nsurl *url, nsurl_component part,
		char *out, size_t cap)
{
	lwc_string *s = nsurl_get_component(url, part);

	out[0] = '\0';
	if (s == NULL) {
		return false;
	}
	snprintf(out, cap, "%.*s", (int)lwc_string_length(s),
			lwc_string_data(s));
	lwc_string_unref(s);
	return true;
}

static bool url_text_fits(const char *s, int avail_w)
{
	if (avail_w <= 0) {
		return true;
	}
	return tk_text_width(tk_theme_default(), s) <= avail_w;
}

/* Shorten s in place until it fits avail_w with an ellipsis
 * appended; cuts only at UTF-8 character boundaries. */
static void url_truncate(char *s, int avail_w)
{
	const tk_theme *th = tk_theme_default();
	int ell_w = tk_text_width(th, "…");
	size_t len = strlen(s);

	while (len > 0 &&
	       tk_text_width(th, s) + ell_w > avail_w) {
		len--;
		while (len > 0 && (s[len] & 0xC0) == 0x80) {
			len--;
		}
		s[len] = '\0';
	}
	strcat(s, "…");
}

/* The display form is recomputed only when its inputs change:
 * the tab's URL, its title (internal pages display by title), or
 * the field's arranged width (the elision target). */
static char url_disp_key[2304];
static char url_disp_cache[1024];

/* Build the steady-state display form of a tab's URL.
 * Rules (report section 9.3-6, from Chromium's GetURLForDisplay):
 *   https/ftp  host[:port] + path, scheme omitted, "www." omitted
 *   http       scheme kept (the text field has no "Not secure"
 *              label slot; the visible scheme is the warning)
 *   file       the file name only (Chrome's File chip equivalent)
 *   internal   (resource:, about:, data:, ...) the page title
 * Overlong forms lose the query first, then the path's middle
 * segments ("host/…/file"), then truncate with an ellipsis. */
static void url_display_form(struct gui_window *gw, char *out, size_t cap)
{
	const char *full = gw->url_text;
	tk_rect fr = tk_widget_rect(brain_fe.url_field);
	int avail = fr.w > 0 ? fr.w - 16 : 0; /* field inner slack */
	char key[2304];
	nsurl *url = NULL;
	char scheme[32], host[256], port[16], path[1024], query[512];
	bool has_host, has_port, has_path, has_query;

	snprintf(key, sizeof(key), "%s\n%s\n%d",
			full != NULL ? full : "", tab_title(gw), fr.w);
	if (strcmp(key, url_disp_key) == 0) {
		snprintf(out, cap, "%s", url_disp_cache);
		return;
	}

	out[0] = '\0';
	scheme[0] = host[0] = port[0] = path[0] = query[0] = '\0';
	has_host = has_port = has_path = has_query = false;
	if (full != NULL && full[0] != '\0' &&
	    nsurl_create(full, &url) == NSERROR_OK) {
		url_component(url, NSURL_SCHEME, scheme, sizeof(scheme));
		has_host = url_component(url, NSURL_HOST, host,
				sizeof(host));
		has_port = url_component(url, NSURL_PORT, port,
				sizeof(port));
		has_path = url_component(url, NSURL_PATH, path,
				sizeof(path));
		has_query = url_component(url, NSURL_QUERY, query,
				sizeof(query));
		nsurl_unref(url);
		url = NULL;
	}

	if (full == NULL || full[0] == '\0') {
		/* nothing loaded yet: leave the placeholder to speak */
	} else if (scheme[0] == '\0') {
		/* unparseable: show as-is */
		snprintf(out, cap, "%s", full);
	} else if (strcmp(scheme, "file") == 0) {
		const char *base = has_path ? path : "";
		const char *slash = strrchr(base, '/');

		if (slash != NULL && slash[1] != '\0') {
			base = slash + 1;
		} else if (slash != NULL && slash != base) {
			/* trailing slash: the last directory name */
			const char *end = slash;
			const char *p;
			for (p = base; p < end; p++) {
				if (*p == '/') {
					slash = p;
				}
			}
			snprintf(out, cap, "%.*s",
					(int)(end - (slash + 1)), slash + 1);
			base = NULL;
		}
		if (base != NULL) {
			snprintf(out, cap, "%s",
					base[0] != '\0' ? base : full);
		}
		if (!url_text_fits(out, avail)) {
			url_truncate(out, avail);
		}
	} else if (!has_host) {
		/* internal / non-hierarchical page: title, not URL */
		snprintf(out, cap, "%s", tab_title(gw));
		if (!url_text_fits(out, avail)) {
			url_truncate(out, avail);
		}
	} else {
		char head[320];
		const char *h = host;
		const char *p = (has_path && strcmp(path, "/") != 0) ?
				path : "";

		if (strncmp(h, "www.", 4) == 0 && h[4] != '\0') {
			h += 4; /* trivial subdomain (Chrome rule) */
		}
		snprintf(head, sizeof(head), "%s%s%s%s",
				strcmp(scheme, "http") == 0 ?
					"http://" : "",
				h, has_port ? ":" : "",
				has_port ? port : "");
		snprintf(out, cap, "%s%s%s%s", head, p,
				has_query ? "?" : "",
				has_query ? query : "");
		if (!url_text_fits(out, avail) && has_query) {
			/* the query is the first thing to go */
			snprintf(out, cap, "%s%s", head, p);
		}
		if (!url_text_fits(out, avail) && has_path) {
			/* then the path's middle segments */
			const char *last = strrchr(path, '/');
			if (last != NULL && last != path) {
				snprintf(out, cap, "%s/…/%s",
						head, last + 1);
			}
		}
		if (!url_text_fits(out, avail)) {
			url_truncate(out, avail);
		}
	}

	snprintf(url_disp_key, sizeof(url_disp_key), "%s", key);
	snprintf(url_disp_cache, sizeof(url_disp_cache), "%s", out);
}

/* Put the display form into the field (unless the user is
 * editing); a no-op when the field already shows it. */
static void url_field_refresh(void)
{
	struct gui_window *gw = brain_fe.active;
	char disp[1024];
	char cur[1024];

	if (brain_fe.url_field == NULL || brain_fe.url_editing) {
		return;
	}
	if (gw == NULL) {
		disp[0] = '\0';
	} else {
		url_display_form(gw, disp, sizeof(disp));
	}
	tk_textfield_text(brain_fe.url_field, cur, sizeof(cur));
	if (strcmp(cur, disp) != 0) {
		tk_textfield_set_text(brain_fe.url_field, disp);
	}
}

void brain_url_begin_edit(void)
{
	struct gui_window *gw = brain_fe.active;

	if (gw == NULL || brain_fe.url_field == NULL ||
	    brain_fe.url_editing) {
		return;
	}
	brain_fe.url_editing = true;
	tk_textfield_set_text(brain_fe.url_field,
			gw->url_text != NULL ? gw->url_text : "");
	tc_select_all(tk_textfield_buffer(brain_fe.url_field));
}

void brain_url_end_edit(void)
{
	if (!brain_fe.url_editing) {
		return;
	}
	brain_fe.url_editing = false;
	url_field_refresh();
}

void brain_chrome_sync(void)
{
	struct gui_window *gw = brain_fe.active;
	const tk_theme *th = tk_theme_default();

	if (brain_fe.root == NULL) {
		return;
	}
	rebuild_tab_strip();
	/* the strip exists only to switch between two tabs; with
	 * one tab it would be 48px of pure waste */
	tk_set_visible(brain_fe.tabstrip, brain_fe.n_windows > 1);

	if (gw != NULL) {
		tk_set_enabled(brain_fe.back_btn,
				browser_window_history_back_available(gw->bw));
		tk_set_enabled(brain_fe.fwd_btn,
				browser_window_history_forward_available(
					gw->bw));
		brain_set_status(gw, gw->status);
	} else {
		tk_set_enabled(brain_fe.back_btn, false);
		tk_set_enabled(brain_fe.fwd_btn, false);
	}
	/* steady-state display form (skipped while editing) */
	url_field_refresh();

	/* reload button doubles as stop while loading (the glyph
	 * is the mode's set: Material refresh/close, Fluent
	 * arrow_clockwise/dismiss in WinUI mode) */
	if (gw != NULL && gw->throbbing) {
		tk_button_set_icon(brain_fe.reload_btn,
				icon_default(ICON_SLOT_STOP, brain_icon_stop,
					brain_icon_winui_stop),
				BRAIN_ICON_SIZE, BRAIN_ICON_SIZE);
		tk_set_visible(brain_fe.progress, true);
		tk_progress_set_value(brain_fe.progress,
				((gw->throbber_phase % 8) + 1) / 8.0f);
	} else {
		tk_button_set_icon(brain_fe.reload_btn,
				icon_default(ICON_SLOT_RELOAD,
					brain_icon_reload,
					brain_icon_winui_reload),
				BRAIN_ICON_SIZE, BRAIN_ICON_SIZE);
		tk_set_visible(brain_fe.progress, false);
	}
	/* WinUI favourite button: accent ink while the current
	 * page is bookmarked.  The established Fluent set has no
	 * separate filled star, so the state is carried by the
	 * tint, not by a substitute glyph. */
	if (brain_fe.fav_btn != NULL) {
		bool bookmarked = false;
		if (gw != NULL) {
			nsurl *url = browser_window_access_url(gw->bw);
			if (url != NULL) {
				bookmarked = hotlist_has_url(url);
			}
		}
		tk_button_set_icon(brain_fe.fav_btn,
				icon_for(ICON_SLOT_STAR, brain_icon_star,
					brain_icon_winui_star,
					bookmarked ? th->accent :
						th->text_dim),
				BRAIN_ICON_SIZE, BRAIN_ICON_SIZE);
	}
	(void)th;
	tk_root_layout(brain_fe.root, brain_fe.width, brain_fe.height);
	brain_chrome_layout();
}

/* Status text is transient (report section 9.3-5): the bubble
 * shows while the active tab is loading and for STATUS_HIDE_MS
 * after the text last changed, then removes itself.  Before the
 * redesign the final status ("Done (0.0s)") stayed on screen
 * forever, reading as a permanent status bar squatting on the
 * page.  The hide timer is only (re)armed when the text changes
 * or the bubble appears, so the throbber-cadence syncs in
 * brain_chrome_sync do not postpone it indefinitely; while the
 * tab is still loading the timer re-arms itself instead of
 * hiding. */
#define STATUS_HIDE_MS 2500
static char status_shown[512];

static void status_hide_cb(void *p)
{
	(void)p;
	if (brain_fe.status_bubble == NULL) {
		return;
	}
	if (brain_fe.active != NULL && brain_fe.active->throbbing) {
		brain_schedule(STATUS_HIDE_MS, status_hide_cb, NULL);
		return;
	}
	tk_set_visible(brain_fe.status_bubble, false);
	status_shown[0] = '\0';
}

void brain_set_status(struct gui_window *gw, const char *text)
{
	if (gw != brain_fe.active || brain_fe.status_bubble == NULL) {
		return;
	}
	if (text == NULL || text[0] == '\0') {
		tk_set_visible(brain_fe.status_bubble, false);
		status_shown[0] = '\0';
		brain_schedule(-1, status_hide_cb, NULL);
		return;
	}
	if (!tk_is_visible(brain_fe.status_bubble) ||
	    strcmp(text, status_shown) != 0) {
		snprintf(status_shown, sizeof(status_shown), "%s", text);
		tk_label_set_text(brain_fe.status_bubble, text);
		tk_set_visible(brain_fe.status_bubble, true);
		brain_chrome_layout();
		brain_schedule(STATUS_HIDE_MS, status_hide_cb, NULL);
	}
}

