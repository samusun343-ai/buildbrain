static void on_setting_toggle(tk_widget *w, void *ud)
{
	(void)ud;
	if (w == set_js) {
		nsoption_set_bool(enable_javascript,
				tk_checkbox_checked(w));
	} else if (w == set_images) {
		nsoption_set_bool(suppress_images,
				!tk_checkbox_checked(w));
	}
}

/* Text size = page scale.  The frontend default is 125% (see
 * brainreg.c); the choices here rewrite the core scale option,
 * which brain_brainreg_store() persists as browser.default_scale,
 * and apply immediately to every open window. */
static const int scale_choices[] = { 100, 125, 150 };
static const char *scale_names[] = { "小", "標準", "大" };

static void scale_button_sync(void)
{
	char label[64];
	int cur = nsoption_int(scale);
	size_t i;

	for (i = 0; i < sizeof(scale_choices) / sizeof(scale_choices[0]);
	     i++) {
		if (scale_choices[i] == cur) {
			snprintf(label, sizeof(label), "文字の大きさ: %s (%d%%)",
					scale_names[i], cur);
			tk_button_set_label(set_scale_btn, label);
			return;
		}
	}
	snprintf(label, sizeof(label), "文字の大きさ: %d%%", cur);
	tk_button_set_label(set_scale_btn, label);
}

static void on_scale_cycle(tk_widget *w, void *ud)
{
	int cur = nsoption_int(scale);
	int next = scale_choices[1]; /* unknown value -> standard */
	size_t i;
	struct gui_window *gw;

	(void)w; (void)ud;
	for (i = 0; i < sizeof(scale_choices) / sizeof(scale_choices[0]);
	     i++) {
		if (scale_choices[i] == cur) {
			next = scale_choices[(i + 1) %
				(sizeof(scale_choices) /
				 sizeof(scale_choices[0]))];
			break;
		}
	}
	nsoption_set_int(scale, next);
	for (gw = brain_fe.windows; gw != NULL; gw = gw->next) {
		if (gw->bw != NULL) {
			browser_window_set_scale(gw->bw,
					next / 100.0f, true);
		}
	}
	scale_button_sync();
}

static void open_settings(void)
{
	tk_checkbox_set_checked(set_js,
			nsoption_bool(enable_javascript));
	tk_checkbox_set_checked(set_images,
			!nsoption_bool(suppress_images));
	scale_button_sync();
	tk_dialog_show(brain_fe.root, set_dialog);
}

