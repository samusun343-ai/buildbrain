struct tab_ref {
	struct gui_window *gw;
};

static struct tab_ref tab_refs[BRAIN_MAX_TABS];

/* the strip is rebuilt only when its signature changes: tab
 * count, active tab, or any title (chrome_sync runs at throbber
 * cadence while loading and must not churn widgets) */
static char tab_signature[1024];

static void on_tab_click(tk_widget *w, void *ud)
{
	struct tab_ref *ref = ud;
	(void)w;
	if (ref != NULL && ref->gw != NULL) {
		brain_set_active_window(ref->gw);
	}
}

static void on_tab_close(tk_widget *w, void *ud)
{
	struct tab_ref *ref = ud;
	(void)w;
	if (ref != NULL && ref->gw != NULL && ref->gw->bw != NULL) {
		browser_window_destroy(ref->gw->bw);
	}
}

static const char *tab_title(struct gui_window *gw)
{
	const char *title = browser_window_get_title(gw->bw);
	if (title == NULL || title[0] == '\0') {
		title = (gw->url_text != NULL && gw->url_text[0] != '\0') ?
			gw->url_text : "新規タブ";
	}
	return title;
}

static void rebuild_tab_strip(void)
{
	struct gui_window *order[BRAIN_MAX_TABS];
	struct gui_window *gw;
	char sig[1024];
	size_t off = 0;
	int n = 0, i;

	/* the window list is newest-first; the strip shows the
	 * oldest tab first */
	for (gw = brain_fe.windows; gw != NULL && n < BRAIN_MAX_TABS;
	     gw = gw->next) {
		order[brain_fe.n_windows - 1 - n] = gw;
		n++;
	}

	sig[0] = '\0';
	for (i = 0; i < n; i++) {
		off += snprintf(sig + off, sizeof(sig) - off, "%s|%c;",
				tab_title(order[i]),
				order[i] == brain_fe.active ? '*' : ' ');
		if (off >= sizeof(sig)) {
			break;
		}
	}
	if (strcmp(sig, tab_signature) == 0 && n > 0) {
		return;
	}
	snprintf(tab_signature, sizeof(tab_signature), "%s", sig);

	while (tk_child_count(brain_fe.tab_row) > 0) {
		tk_widget *ch = tk_child_at(brain_fe.tab_row, 0);
		tk_remove_child(brain_fe.tab_row, ch);
		tk_widget_free(ch);
	}

	for (i = 0; i < n; i++) {
		tk_widget *seg, *btn, *close;
		gw = order[i];
		tab_refs[i].gw = gw;

		seg = tk_box_new(TK_DIR_HORIZONTAL, 0, 0);
		/* Tab width follows the title, capped like Chrome's.
		 * The cap is also the fit guarantee: with at most
		 * BRAIN_MAX_TABS (2) tabs the strip content is at
		 * most 2*300 + 8 spacing = 608px wide, inside any
		 * realistic window, so nothing can be pushed past
		 * the right edge (the pre-redesign strip let a
		 * full-width tab shove "+" off-screen).  The +96
		 * covers the 48px close zone and the button's own
		 * horizontal padding. */
		{
			const tk_theme *th = tk_theme_default();
			int tw = tk_text_width(th, tab_title(gw)) + 96;
			if (tw < 160) tw = 160;
			if (tw > 300) tw = 300;
			tk_widget_set_min_size(seg, tw, 48);
		}

		btn = tk_button_new(tab_title(gw));
		tk_set_flex(btn, 1);
		/* Filled, never outlined: the active tab carries the
		 * toolbar's surface colour (they are one layer), an
		 * inactive tab is flat paint on the strip's tonal
		 * backdrop. */
		tk_button_set_flat(btn, true);
		if (gw == brain_fe.active) {
			const tk_theme *th = tk_theme_default();
			tk_button_set_face(btn, &th->surface);
		}
		tk_button_set_on_click(btn, on_tab_click, &tab_refs[i]);

		close = tk_button_new("×");
		tk_widget_set_min_size(close, 48, 48);
		tk_button_set_flat(close, true);
		tk_button_set_on_click(close, on_tab_close, &tab_refs[i]);

		tk_add_child(seg, btn);
		tk_add_child(seg, close);
		tk_add_child(brain_fe.tab_row, seg);
	}

	{
		/* leftover space stays empty on the right; the new
		 * tab action lives in the toolbar now */
		tk_widget *spacer = tk_box_new(TK_DIR_HORIZONTAL, 0, 0);
		tk_set_flex(spacer, 1);
		tk_add_child(brain_fe.tab_row, spacer);
	}
}

