static void on_back(tk_widget *w, void *ud)
{
	(void)w; (void)ud;
	if (brain_fe.active != NULL) {
		browser_window_history_back(brain_fe.active->bw, false);
	}
}

static void on_forward(tk_widget *w, void *ud)
{
	(void)w; (void)ud;
	if (brain_fe.active != NULL) {
		browser_window_history_forward(brain_fe.active->bw, false);
	}
}

static void on_reload_stop(tk_widget *w, void *ud)
{
	(void)w; (void)ud;
	if (brain_fe.active == NULL) {
		return;
	}
	if (brain_fe.active->throbbing) {
		browser_window_stop(brain_fe.active->bw);
	} else {
		browser_window_reload(brain_fe.active->bw, false);
	}
}

static void go_home(void)
{
	const char *home = nsoption_charp(homepage_url);
	if (home == NULL || home[0] == '\0') {
		home = "resource:welcome.html";
	}
	brain_navigate(home);
}

static void on_home_btn(tk_widget *w, void *ud)
{
	(void)w; (void)ud;
	go_home();
}

/* WinUI (Edge) favourite button: toggle the current page's
 * bookmark, the same action as the menu's bookmark item. */
static void on_fav_toggle(tk_widget *w, void *ud)
{
	struct gui_window *gw = brain_fe.active;
	(void)w; (void)ud;
	if (gw != NULL) {
		nsurl *url = browser_window_access_url(gw->bw);
		if (url != NULL) {
			if (hotlist_has_url(url)) {
				hotlist_remove_url(url);
			} else {
				hotlist_add_url(url);
			}
		}
	}
}

static void on_new_tab(tk_widget *w, void *ud)
{
	const char *home = nsoption_charp(homepage_url);
	(void)w; (void)ud;
	if (home == NULL || home[0] == '\0') {
		home = "resource:welcome.html";
	}
	brain_open_tab(home, false);
}

