/* Mark every open overlay for repaint.  The present cycle in
 * gui.c redraws page damage AFTER the root paint (the root
 * bg-fills the page area), which would erase the parts of a
 * menu/dialog that overlap the page; gui.c calls this after
 * the page redraw so the overlays are painted once more, on
 * top.  Only the overlay rects are invalidated, so the extra
 * pass costs one overlay-sized paint per frame with page
 * damage while an overlay is up. */
void brain_overlays_invalidate(void)
{
	if (brain_fe.root == NULL) {
		return;
	}
	if (menu_widget != NULL &&
	    tk_menu_is_open(brain_fe.root, menu_widget)) {
		tk_widget_invalidate(menu_widget);
	}
	if (bm_dialog != NULL &&
	    tk_dialog_is_shown(brain_fe.root, bm_dialog)) {
		tk_widget_invalidate(bm_dialog);
	}
	if (hist_dialog != NULL &&
	    tk_dialog_is_shown(brain_fe.root, hist_dialog)) {
		tk_widget_invalidate(hist_dialog);
	}
	if (set_dialog != NULL &&
	    tk_dialog_is_shown(brain_fe.root, set_dialog)) {
		tk_widget_invalidate(set_dialog);
	}
	/* the transient page-area overlays live in the page holder,
	 * so page damage erases them just like a menu */
	if (brain_fe.progress != NULL &&
	    tk_is_visible(brain_fe.progress)) {
		tk_widget_invalidate(brain_fe.progress);
	}
	if (brain_fe.status_bubble != NULL &&
	    tk_is_visible(brain_fe.status_bubble)) {
		tk_widget_invalidate(brain_fe.status_bubble);
	}
}
