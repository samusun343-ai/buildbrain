static nserror collect_address(void *ctx, struct nsurl *url,
		const char *title)
{
	(void)ctx;
	list_push(nsurl_access(url), title);
	return NSERROR_OK;
}

static nserror collect_folder_enter(void *ctx, const char *title)
{
	(void)ctx; (void)title;
	return NSERROR_OK;
}

static nserror collect_folder_leave(void *ctx)
{
	(void)ctx;
	return NSERROR_OK;
}

static void open_bookmarks(void)
{
	const char *items[MAX_LIST_ENTRIES];
	const char *subs[MAX_LIST_ENTRIES];
	int i;

	list_clear();
	hotlist_iterate(NULL, collect_folder_enter, collect_address,
			collect_folder_leave);
	for (i = 0; i < list_count; i++) {
		items[i] = list_titles[i];
		subs[i] = list_urls[i];
	}
	tk_listview_set_items(bm_list, items, (size_t)list_count);
	tk_listview_set_subitems(bm_list, subs, (size_t)list_count);
	tk_dialog_show(brain_fe.root, bm_dialog);
}

static bool collect_history(nsurl *url, const struct url_data *data)
{
	list_push(nsurl_access(url),
			data != NULL ? data->title : NULL);
	return true;
}

static void open_history(void)
{
	const char *items[MAX_LIST_ENTRIES];
	const char *subs[MAX_LIST_ENTRIES];
	int i;

	list_clear();
	urldb_iterate_entries(collect_history);
	for (i = 0; i < list_count; i++) {
		items[i] = list_titles[i];
		subs[i] = list_urls[i];
	}
	tk_listview_set_items(hist_list, items, (size_t)list_count);
	tk_listview_set_subitems(hist_list, subs, (size_t)list_count);
	tk_dialog_show(brain_fe.root, hist_dialog);
}

static void on_list_activate(tk_widget *w, void *ud)
{
	tk_widget *dlg = ud;
	int sel = tk_listview_selected(w);
	if (sel >= 0 && sel < list_count && list_urls[sel] != NULL) {
		brain_navigate(list_urls[sel]);
	}
	tk_dialog_close(brain_fe.root, dlg);
}

static void on_dialog_close(tk_widget *w, void *ud)
{
	(void)w;
	tk_dialog_close(brain_fe.root, (tk_widget *)ud);
}

