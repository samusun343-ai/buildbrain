#!/usr/bin/env python3
"""Generate shim/shim_table.h from shim/implemented.txt.

Ordinals come from the QEMU-side project's published static census
(exports-census.json -> coredll.dll -> ordmap, ordinal -> name),
which is byte-identical to the p47 coredll-exports.json derived
independently from the same CE image. The generated header is
committed; rerun this only when implemented.txt changes.

Usage: gen_shim_table.py [path-to-exports-census.json]
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAYER = os.path.dirname(HERE)
DEFAULT_CENSUS = os.path.expanduser(
    "~/workspace/goals/sharp-brain-full-virtualization/hidden_files/"
    "p45work/static/exports-census.json")


def main():
    census_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CENSUS
    ec = json.load(open(census_path))
    ordmap = {int(k): v for k, v in ec["coredll.dll"]["ordmap"].items()}
    name2ord = {v: k for k, v in ordmap.items()}
    maxord = max(ordmap)

    names = []
    with open(os.path.join(LAYER, "shim", "implemented.txt")) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                names.append(line)
    missing = [n for n in names if n not in name2ord]
    if missing:
        print("ERROR: names not in coredll ordmap:", missing)
        return 1

    out = []
    out.append("/* GENERATED by tools/gen_shim_table.py -- do not edit. */")
    out.append("#ifndef BRAINCE_SHIM_TABLE_H")
    out.append("#define BRAINCE_SHIM_TABLE_H")
    out.append("")
    out.append("struct ce_shim_desc { const char *ce_name; "
               "unsigned ordinal; };")
    out.append("static const struct ce_shim_desc ce_shim_descs[] = {")
    for n in names:
        out.append(f'\t{{ "{n}", {name2ord[n]} }},')
    out.append("};")
    out.append(f"#define CE_SHIM_DESC_COUNT "
               f"(sizeof(ce_shim_descs)/sizeof(ce_shim_descs[0]))")
    out.append("")
    out.append("/* ordinal -> index into ce_shim_table, -1 = unimplemented */")
    idx = [-1] * (maxord + 1)
    for i, n in enumerate(names):
        idx[name2ord[n]] = i
    out.append(f"static const short ce_ord_index[{maxord + 1}] = {{")
    for i in range(0, len(idx), 12):
        out.append("\t" + ",".join(str(v) for v in idx[i:i + 12]) + ",")
    out.append("};")
    out.append(f"#define CE_ORD_INDEX_MAX {maxord}")
    out.append("")
    out.append("#endif")
    dst = os.path.join(LAYER, "shim", "shim_table.h")
    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {dst}: {len(names)} syms, ordinals up to {maxord}")

    # Function-pointer table: included at the end of coredll_shim.c,
    # after the ce_* definitions, so no forward declarations clash.
    out2 = []
    out2.append("/* GENERATED by tools/gen_shim_table.py -- do not edit.")
    out2.append(" * Included by coredll_shim.c after the ce_* definitions. */")
    out2.append("struct ce_shim_sym { const char *ce_name; "
                "unsigned ordinal; void *fn; };")
    out2.append("static const struct ce_shim_sym ce_shim_table[] = {")
    for n in names:
        out2.append(f'\t{{ "{n}", {name2ord[n]}, (void *)ce_{n} }},')
    out2.append("};")
    out2.append("#define CE_SHIM_TABLE_COUNT "
                "(sizeof(ce_shim_table)/sizeof(ce_shim_table[0]))")
    dst2 = os.path.join(LAYER, "shim", "shim_fns.h")
    with open(dst2, "w") as f:
        f.write("\n".join(out2) + "\n")
    print(f"wrote {dst2}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
