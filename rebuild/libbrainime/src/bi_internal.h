/* libbrainime internals — shared between dict.c, conn.c, engine.c */
#ifndef BI_INTERNAL_H
#define BI_INTERNAL_H

#include "brainime.h"
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* ---- bit vector with sampled rank/select index (dict.c) ---- */
typedef struct {
	const uint8_t *bits;
	uint32_t nbits;
	uint32_t *rank_idx;	/* rank1 sample every 512 bits */
	uint32_t *sel1_idx;	/* position of every 256th 1-bit */
	uint32_t nsel1;
	uint32_t *sel0_idx;	/* position of every 256th 0-bit */
	uint32_t nsel0;
} bitvec;

int  bv_build(bitvec *bv, const uint8_t *bits, uint32_t nbits);
void bv_free(bitvec *bv);
uint32_t bv_rank1(const bitvec *bv, uint32_t p);   /* ones in [0..p]; p may be UINT32_MAX -> 0 */
uint32_t bv_select1(const bitvec *bv, uint32_t k); /* pos of k-th 1-bit, k 1-indexed; UINT32_MAX if none */
uint32_t bv_select0(const bitvec *bv, uint32_t k); /* pos of k-th 0-bit, k 0-indexed; UINT32_MAX if none */
int  bv_get(const bitvec *bv, uint32_t p);

/* ---- LOUDS trie (dict.c) ---- */
typedef struct {
	uint32_t n_nodes;
	uint32_t label_bytes;
	uint32_t n_term;
	bitvec louds;
	const uint8_t *labels;	/* (n_nodes-1) * label_bytes */
	bitvec terminal;
	const uint8_t *counts;	/* reading trie only: n_term bytes */
} trie;

uint32_t trie_label(const trie *t, uint32_t node);
uint32_t trie_parent(const trie *t, uint32_t v);
/* Iterate children of v: callback per (child_node, label). */
void trie_children(const trie *t, uint32_t v,
		   void (*cb)(void *ctx, uint32_t child, uint32_t label),
		   void *ctx);

/* ---- dictionary (dict.c) ---- */
struct bi_dict {
	uint8_t *map;
	size_t map_len;
	/* codebook: code -> utf8 string (owned copies) */
	char **book;
	uint32_t *book_cp;	/* code -> codepoint */
	uint32_t nchars;
	/* codepoint -> code hash (open addressing, -1 empty) */
	int32_t *cp_hash;
	uint32_t cp_hash_size;
	trie rd, sf;
	/* token index, decoded once at load from the varint stream:
	 * 180k entries * 6 B — the only non-trivial RAM the engine
	 * adds on top of the shared mmap. */
	uint32_t *tok_sid;
	uint8_t *tok_pos;
	uint8_t *tok_cost;
	uint32_t *tok_first;	/* per reading terminal rank: first token idx; size n_term+1 */
	const int8_t *conn;	/* BIDF conn section (256x256), may be all zero */
	int conn_from_dict;
	/* M2 sidecar (.bisc, generated by tools/gen_sidecar.py):
	 * per-token mozc lid/rid + mozc's real connection matrix,
	 * all pointing into a second MAP_SHARED mapping so the
	 * resident cost stays at the pages actually touched. */
	uint8_t *sc_map;
	size_t sc_len;
	const uint16_t *sc_lid;	/* n_entries */
	const uint16_t *sc_rid;	/* n_entries */
	const uint16_t *sc_cls;	/* 256 * (lid, rid) representatives */
	const uint8_t *sc_matrix; /* sc_n_ids * sc_n_ids, res sc_res */
	uint32_t sc_n_ids;
	uint32_t sc_res;
	int have_sidecar;
	bi_stats stats;
	/* ---- M3: BIDF v3 (single file; every section is read in
	 * place from the same MAP_SHARED mapping — the loader makes
	 * NO bulk copy of any section) ---- */
	int is_v3;
	const uint8_t *v3_conn;		/* CONN payload after its header:
					   nibble-packed matrix */
	const uint16_t *v3_conn_lut;	/* 16 decode values (/64 domain) */
	const uint8_t *conn_ptr;	/* region for resident-page stats:
					   v3 CONN section or .bisc matrix */
	size_t conn_len;
	/* SUPP: sorted records, binary-searched in the mapping */
	const uint32_t *supp_offs;	/* n_supp + 1 offsets */
	const uint8_t *supp_recs;
	uint32_t n_supp;
	/* BIGR: open-addressing table probed in the mapping */
	const uint8_t *bigr_slots;	/* 8-byte slots */
	uint32_t bigr_nslots;
	/* RNK: reranker weights, pointed into the mapping */
	const float *rnk_w;
	uint32_t rnk_nfeat;
	/* surface materialisation cache: bounded, direct-mapped
	 * (the ONLY process-side cache of dictionary-derived
	 * strings; surfaces repeat heavily across candidate
	 * enumeration).  Cap is BI_SURF_CACHE (default 1024 entries,
	 * rounded up to a power of two; 0 disables).  One probe per
	 * lookup — an earlier linear-scan LRU measured SLOWER than
	 * no cache (9.2 ms vs 6.8 ms mean conversion), so lookup
	 * cost, not just hit rate, is part of the design. */
	/* M4: deferred CRC32 verification state (v3 only).
	 * Sections the loader itself parses at open (DICT) and the
	 * small control sections (CLSREP, RNK, META) are verified
	 * at open exactly as in M3.  The large data sections that
	 * are only ever read through engine accessors (TOKID,
	 * CONN, SUPP, BIGR) are verified at first use, before any
	 * conversion touches them: corruption is still always
	 * detected before unverified bytes influence a result,
	 * only the timing moves from open to first conversion.
	 * BI_CRC_FULL=1 restores the M3 verify-everything-at-open
	 * behaviour. */
	const uint8_t *v3_sec_ptr[10];
	uint32_t v3_sec_len[10];
	uint32_t v3_sec_crc[10];
	uint8_t v3_verified[10];	/* per section id */
	int v3_broken;		/* a deferred CRC failed */
	char **surf_cache_str;
	uint32_t *surf_cache_sid;
	uint32_t surf_cache_cap;	/* power of two */
	unsigned long surf_hits, surf_misses;
};

struct bi_engine {
	struct bi_dict d;
	/* Learning: open-addressing table of "reading\tsurface"
	 * keys with commit counts.  M3 persistence is an append-only
	 * journal (see engine.c): records are appended one line per
	 * commit and fsync'd; a torn final line after a power cut is
	 * ignored at load; compaction rewrites via temp file +
	 * rename when the journal outgrows its budget. */
	char *learn_path;
	char **learn_keys;
	int *learn_counts;
	uint32_t learn_mask;	/* table size - 1; 0 = not allocated */
	int learn_n;
	void *learn_fp;		/* FILE* kept open for appending */
	long learn_lines;	/* valid journal lines on disk */
};

/* learning (engine.c) */
int  bi_learn_bonus(bi_engine *e, const char *reading, const char *surface);
void bi_learn_record(bi_engine *e, const char *reading, const char *surface);

/* ---- M3 accessors (dict.c) ---- */
/* M4: verify any pending v3 sections (see above).  Returns 0
 * when every section is verified (or the file is not v3),
 * -1 when a CRC mismatched (dict is then marked broken and
 * conversions fail rather than convert with corrupt data). */
int  bi_dict_verify_pending(struct bi_dict *d);
/* Bytes still unverified (0 once verification is complete). */
size_t bi_dict_unverified_bytes(const struct bi_dict *d);
/* Connection matrix value in the /64 domain, from either the
 * .bisc u8 plane or the v3 nibble-packed CONN section. */
int  bi_dict_conn_raw(const struct bi_dict *d, int rid, int lid);
/* Supplement lookup: records whose reading equals the span
 * cps[0..len).  Call with idx=0,1,... until it returns 0.
 * On a hit fills the cls and cost fields (dictionary cost byte)
 * and either the surf/surf_len fields (bytes inside the mapping,
 * NOT NUL-terminated) or sets is_kata (surface is the katakana
 * form of the reading). */
struct bi_supp_hit {
	const uint8_t *surf;
	int surf_len;
	int is_kata;
	int cls;
	int cost;
};
int  bi_dict_supp(const struct bi_dict *d, const uint32_t *cps, int len,
		  int idx, struct bi_supp_hit *out);
/* Bigram score for (prev, cur) morpheme (reading, surface) pairs;
 * -1 when absent.  BOS/EOS use the literal strings "<BOS>"/"<EOS>"
 * for both reading and surface. */
int  bi_dict_bigram(const struct bi_dict *d, const char *pr,
		    const char *ps, const char *cr, const char *cs);
/* Named region of the dictionary mapping (for resident-page
 * measurement): "file", "conn".  Returns 0 on success. */
int  bi_dict_region(const struct bi_dict *d, const char *name,
		    const uint8_t **ptr, size_t *len);

/* ---- M3 reranker (engine.c) ---- */
#define BI_RERANK_NFEAT 26
#define BI_RERANK_MAXPATH 64	/* M5: 24 -> 64 (pool containment) */
typedef struct {
	char *text;			/* malloc'd full-surface string */
	long cost;			/* Viterbi cost */
	double feat[BI_RERANK_NFEAT];
} bi_pathinfo;
/* Collect up to `max` best Viterbi paths of `reading` with their
 * reranker feature vectors (viterbi order).  Used by the host-side
 * trainer; the engine itself uses the same feature code when a
 * BIDF v3 RNK section is present. */
int  bi_internal_collect(bi_engine *e, const char *reading,
			 bi_pathinfo *out, int max);
void bi_internal_free_paths(bi_pathinfo *p, int n);

/* Left context carried across a session commit: the committed
 * segment acts as the virtual left neighbour of the remainder's
 * first node, instead of BOS. */
typedef struct {
	int pos;		/* BIDF class of the committed segment */
	uint16_t lid, rid;	/* mozc ids (sidecar mode) */
	uint32_t last_cp;	/* last codepoint of its reading */
	int reading_len;	/* its reading length in chars */
	const char *surface;	/* its surface (rule-model form check) */
} bi_leftctx;

int  bi_dict_open(struct bi_dict *d, const char *path);
void bi_dict_close(struct bi_dict *d);
int  bi_dict_encode_char(const struct bi_dict *d, uint32_t cp); /* code or -1 */
/* Materialise surface id into buf.  Returns byte length or -1. */
int  bi_dict_surface(const struct bi_dict *d, uint32_t sid, char *buf, size_t bufsz);
/* Token range for a reading-trie terminal node: rank -> [first, first+count). */
void bi_dict_token_range(const struct bi_dict *d, uint32_t terminal_rank,
			 uint32_t *first, uint32_t *count);
/* Walk the reading trie along codes[0..max_depth), invoking cb at
 * every terminal node (depth = matched character count).  cb
 * returning 0 stops the walk. */
void bi_dict_prefix_walk(const struct bi_dict *d, const uint32_t *codes,
			 int max_depth, void *user,
			 int (*cb)(void *, uint32_t, int));
/* Walk the reading trie along codes[0..len); returns the node id
 * reached, or -1 if the path dies. */
int bi_dict_walk_to(const struct bi_dict *d, const uint32_t *codes, int len);

/* ---- connection cost model (conn.c) ---- */
/* POS class of BOS (left edge) is BI_CLS_BOS; asking for the cost
 * to EOS is bi_conn_eos().  All costs are in engine cost units
 * (word cost = dictionary cost byte * 16). */
#define BI_CLS_BOS 255
int bi_conn_cost(const struct bi_dict *d, int left_cls, int right_cls,
		 uint32_t left_last_cp, uint32_t right_last_cp,
		 const char *left_surface, const char *right_surface);
int bi_conn_eos(int left_cls);

/* UTF-8 helpers (engine.c) */
/* Decode UTF-8 string into codepoints.  Returns count or -1. */
int bi_utf8_decode(const char *s, uint32_t *cps, int max);
/* Encode one codepoint as UTF-8; returns byte length. */
int bi_utf8_encode(uint32_t cp, char *out);
/* Encode codepoint array into a fresh malloc'd UTF-8 string. */
char *bi_utf8_str(const uint32_t *cps, int n);

#endif /* BI_INTERNAL_H */
